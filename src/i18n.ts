/**
 * 界面与地图文字的多语言：中文、English、日本語。
 * 以中文原文为键（源码里写的就是中文），查英文 / 日文词典；缺词时回退到中文原文。
 * 切换语言时通知订阅者（界面由 ui/i18n.ts 的响应式镜像自动重译），不刷新页面。
 */
export type Lang = 'zh' | 'en' | 'ja'
export const LANGS: { id: Lang; label: string }[] = [
  { id: 'zh', label: '中文' },
  { id: 'en', label: 'English' },
  { id: 'ja', label: '日本語' },
]

const isLang = (s: string | null | undefined): s is Lang => s === 'zh' || s === 'en' || s === 'ja'

/** 初始语言：链接里的 lang= 参数 > 上次手动选择 > 浏览器语言偏好列表 > 英文 */
function detect(): Lang {
  const q = /[?&]lang=([a-z]+)/.exec(location.hash + location.search)?.[1]
  if (isLang(q)) return q
  try {
    const saved = localStorage.getItem('lang')
    if (isLang(saved)) return saved
  } catch {
    // 无痕模式等
  }
  for (const l of navigator.languages?.length ? navigator.languages : [navigator.language]) {
    const k = l.toLowerCase().slice(0, 2)
    if (isLang(k)) return k
  }
  return 'en'
}

export let lang: Lang = typeof window !== 'undefined' ? detect() : 'zh'
if (typeof document !== 'undefined' && document.documentElement) document.documentElement.lang = lang === 'zh' ? 'zh-CN' : lang

/** 翻译：key 为中文原文；{name} 形式的占位符用 vars 替换 */
export function t(key: string, vars?: Record<string, string | number>): string {
  let s = lang === 'zh' ? key : ((lang === 'en' ? EN : JA)[key] ?? key)
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
  return s
}

/** 别的模块登记自己的词条（中文、英文、日文）：职业名这类成套的名字放在定义它们的地方 */
export function defineStrings(names: [zh: string, en: string, ja: string][]) {
  for (const [zh, en, ja] of names) {
    EN[zh] ??= en
    JA[zh] ??= ja
  }
}

/** 按指定语言翻译（不看当前界面语言）：离线渲染、导出指定语言的地图时用 */
export function tr(key: string, lg: Lang): string {
  return lg === 'zh' ? key : ((lg === 'en' ? EN : JA)[key] ?? key)
}

const listeners: (() => void)[] = []

export function onLang(cb: () => void) {
  listeners.push(cb)
}

export function setLang(l: Lang) {
  if (l === lang) return
  lang = l
  try {
    localStorage.setItem('lang', l)
  } catch {
    // 忽略
  }
  // 离线脚本（Node）里没有真正的 DOM
  if (typeof document !== 'undefined' && document.documentElement) {
    document.documentElement.lang = l === 'zh' ? 'zh-CN' : l
  }
  for (const cb of listeners) cb()
}

