/**
 * 异世界的五种命名风格（由 ../world.ts 登记）：人类一套完整的词表，精灵、矮人、兽人、魔族各一套小词表。
 * 都以日文为主体：先有片假名的名字，英文、中文是它的两种写法。每个词素带三种写法（英文、中文、日文），
 * 拼接时三种写法同步拼，不走运行时音译，三语一定对得上。中文的写法是专名音译、通名按惯例（魏斯堡、罗森海姆）。
 *
 * 只有人类的风格在世界观的池子里（界面上可选、世界的地名用它）；其余四种由世界观的整体规则分配给相应种族的文化
 *（./setting.ts），只用来起那片文化的城镇名、国名与文化名。
 * 词表的内容与先后、取词根时随机数的抽取顺序都是生成结果的一部分，改动会让旧种子的地名全部改变。
 */

/** 词素：英文、中文、日文三种写法；solo 标出能单独作专名的（用在山脉、森林等地物上：シュヴァルツの森） */
type Morph = [en: string, zh: string, ja: string, solo?: 1]

const tri = (m: Morph): Tri => ({ en: m[0], zh: m[1], ja: m[2] })
const join = (a: Morph, b: Morph): Tri => ({ en: a[0] + b[0], zh: a[1] + b[1], ja: a[2] + b[2] })

/** 拼起来不顺的组合：一个词素以另一个开头或收尾（Steinstein、Falafal、Grenren）、接缝两侧是同一个字母、中文写法叠字（加尔加尔德） */
function clash(a: Morph, b: Morph): boolean {
  const h = a[0].toLowerCase()
  return b[0].startsWith(h) || h.startsWith(b[0]) || h.endsWith(b[0]) || h.endsWith(b[0][0]) || b[1].startsWith(a[1])
}

/** 拉丁语感的专名另外避开接缝处的塞音、擦音相连（Estsia、Altdia） */
function latinClash(a: Morph, b: Morph): boolean {
  if (clash(a, b)) return true
  const last = a[0][a[0].length - 1]
  const first = b[0][0]
  return ('td'.includes(last) && 'tdsz'.includes(first)) || (last === 's' && 'sz'.includes(first))
}

/**
 * 词头加词尾：拼得不顺、或词头在这个取名器里已经用过（seen），就整对重抽（至多 12 次，之后照用）。
 * 词头轮过一遍再从头用：同一个世界里少出现"弗伦迪亚、弗伦格里亚"这样只差词尾的名字
 */
function compound(r: RNG, seen: Set<Morph>, heads: Morph[], tails: Morph[], bad: (a: Morph, b: Morph) => boolean = clash): Tri {
  if (seen.size >= heads.length) seen.clear()
  let a = r.pick(heads)
  let b = r.pick(tails)
  for (let t = 0; t < 12 && (seen.has(a) || bad(a, b)); t++) {
    a = r.pick(heads)
    b = r.pick(tails)
  }
  seen.add(a)
  return join(a, b)
}

