// —— 各种族的小词表：一律是"词头 + 词尾"，各类名字都从同一套里取 ——
/**
 * 种族的命名风格：通名模板沿用人类的，只换文化名的写法（world 一项，起文化名时用）与国名模板。
 * 精灵、矮人的国名在日文里把通名放在前面（エルフ王国イシリエン）：专名也是片假名，接在"エルフ""ドワーフ"前面分不开
 */
function race(o: { id: string; label: string; tip: string; folk: Tpl; realm: Tpl[]; heads: Morph[]; tails: Morph[] }): NamingStyleDef {
  return {
    id: o.id,
    label: o.label,
    tip: o.tip,
    kinds: { ...KINDS, world: [o.folk] },
    realm: o.realm,
    avoidEcho: false,
    roots({ rng: r }) {
      const seen = new Set<Morph>()
      return () => compound(r, seen, o.heads, o.tails)
    },
  }
}

